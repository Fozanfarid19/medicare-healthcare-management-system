/**
 * Returns the single shared MySQLi connection (lazy singleton).
 *
 * @return mysqli
 */
function db()
{
    static $conn = null;

    if ($conn instanceof mysqli) {
        return $conn;
    }

    try {
        $conn = new mysqli(DB_HOST, DB_USER, DB_PASS, DB_NAME, DB_PORT);
        $conn->set_charset('utf8mb4');

        // Keep MySQL's clock identical to PHP's clock so that NOW(),
        // CURDATE() and PHP date() can never disagree during a demo.
        // The offset is generated by PHP and validated against a strict
        // pattern before it is used, so no user input can reach this query.
        $offset = (new DateTime('now', new DateTimeZone(APP_TIMEZONE)))->format('P');
        if (preg_match('/^[+-]\d{2}:\d{2}$/', $offset)) {
            $conn->query("SET time_zone = '" . $offset . "'");
        }
    } catch (Throwable $e) {
        db_fail('Unable to connect to the database.', $e);
    }

    return $conn;
}

/**
 * Central error handler - never leaks raw SQL to the end user.
 */
function db_fail($friendlyMessage, Throwable $e)
{
    error_log('[MediCare DB] ' . $e->getMessage());

    if (APP_DEBUG) {
        $friendlyMessage .= '<br><small><strong>Technical detail:</strong> '
                          . htmlspecialchars($e->getMessage(), ENT_QUOTES, 'UTF-8') . '</small>';
    }

    if (PHP_SAPI === 'cli') {
        exit("DATABASE ERROR: " . $e->getMessage() . PHP_EOL);
    }

    // If the request is AJAX, answer with JSON instead of an HTML page.
    $isAjax = isset($_SERVER['HTTP_X_REQUESTED_WITH'])
           && strtolower($_SERVER['HTTP_X_REQUESTED_WITH']) === 'xmlhttprequest';
    if ($isAjax) {
        header('Content-Type: application/json');
        http_response_code(500);
        echo json_encode(['success' => false, 'message' => strip_tags($friendlyMessage)]);
        exit;
    }

    http_response_code(500);
    echo '<!doctype html><html><head><meta charset="utf-8"><title>Database error</title>'
       . '<style>body{font-family:Segoe UI,Arial,sans-serif;background:#f4f7fb;padding:60px;color:#123}'
       . '.box{max-width:720px;margin:auto;background:#fff;border-radius:12px;padding:32px;'
       . 'box-shadow:0 10px 30px rgba(16,42,67,.08);border-top:5px solid #d9534f}</style></head><body>'
       . '<div class="box"><h2>Database error</h2><p>' . $friendlyMessage . '</p>'
       . '<p>Please make sure <strong>MySQL is running in XAMPP</strong> and that the database '
       . '<code>' . DB_NAME . '</code> has been imported from <code>database/schema.sql</code>.</p>'
       . '<p><a href="' . BASE_URL . 'index.php">Back to home</a></p></div></body></html>';
    exit;
}

// ---------------------------------------------------------------------
// 4. PREPARED-STATEMENT HELPERS
//    Usage:  db_all('SELECT * FROM users WHERE role_id = ?', [$roleId]);
//    Types are detected automatically (i = int, d = float, s = string).
// ---------------------------------------------------------------------

/**
 * Prepares, binds and executes a statement.
 *
 * @param  string $sql    SQL containing ? placeholders
 * @param  array  $params Values for the placeholders
 * @return mysqli_stmt
 */
function db_stmt($sql, array $params = [])
{
    $conn = db();

    try {
        $stmt = $conn->prepare($sql);

        if (!empty($params)) {
            $types = '';
            foreach ($params as $p) {
                if (is_int($p))          { $types .= 'i'; }
                elseif (is_float($p))    { $types .= 'd'; }
                else                     { $types .= 's'; }
            }
            $stmt->bind_param($types, ...$params);
        }

        $stmt->execute();
        return $stmt;
    } catch (Throwable $e) {
        db_fail('The system could not complete that database operation.', $e);
    }
}

/** Returns every matching row as an associative array. */
function db_all($sql, array $params = [])
{
    $stmt = db_stmt($sql, $params);
    $res  = $stmt->get_result();
    $rows = $res ? $res->fetch_all(MYSQLI_ASSOC) : [];
    $stmt->close();
    return $rows;
}

/** Returns the first matching row, or null. */
function db_row($sql, array $params = [])
{
    $stmt = db_stmt($sql, $params);
    $res  = $stmt->get_result();
    $row  = $res ? $res->fetch_assoc() : null;
    $stmt->close();
    return $row ?: null;
}

/** Returns the first column of the first row (handy for COUNT queries). */
function db_scalar($sql, array $params = [], $default = 0)
{
    $row = db_row($sql, $params);
    if (!$row) {
        return $default;
    }
    $value = reset($row);
    return $value === null ? $default : $value;
}

/** Runs INSERT/UPDATE/DELETE and returns the number of affected rows. */
function db_execute($sql, array $params = [])
{
    $stmt     = db_stmt($sql, $params);
    $affected = $stmt->affected_rows;
    $stmt->close();
    return $affected;
}

/** Runs an INSERT and returns the new AUTO_INCREMENT id. */
function db_insert($sql, array $params = [])
{
    $stmt = db_stmt($sql, $params);
    $id   = db()->insert_id;
    $stmt->close();
    return (int) $id;
}

/** True when at least one row matches. */
function db_exists($sql, array $params = [])
{
    return db_row($sql, $params) !== null;
}

